test_that("field mappings serialize through the native layer API", {
  d <- data.frame(east=c(1,2), north=c(2,3), seconds=c(0,.2), athlete=c("a","a"), club="home")
  w <- addIoLayer(myIO(d), "field", label="Match", mapping=list(x_var="east",y_var="north",time="seconds",entity="athlete",team="club"), options=list(pitchLength=105,pitchWidth=68))
  expect_identical(w$x$config$layers[[1]]$type,"field")
  expect_identical(w$x$config$layers[[1]]$mapping$entity,"athlete")
  expect_length(w$x$config$layers[[1]]$data,2)
  expect_error(addIoLayer(myIO(d),"field",label="Match",mapping=list(x_var="east",y_var="north")),"time, entity")
  expect_error(addIoLayer(myIO(d),"field",label="Match",mapping=list(x_var="east",y_var="north",time="missing",entity="athlete")),"existing column")
  expect_error(addIoLayer(w,"point",label="Points",mapping=list(x_var="east",y_var="north")),"incompatible")
})

test_that("field overlay options are validated and serialize as JSON arrays", {
  d <- data.frame(east=c(1,2), north=c(2,3), seconds=c(0,.2), athlete=c("a","b"), club=c("home","away"))
  m <- list(x_var="east",y_var="north",time="seconds",entity="athlete",team="club")
  field <- function(...) addIoLayer(myIO(d), "field", label="Match", mapping=m, options=list(...))
  w <- field(overlays=list(shape=TRUE, separation=FALSE), minPlayers=3, excludeEntities="a", metricWindow=c(0, .2))
  o <- w$x$config$layers[[1]]$options
  expect_identical(o$overlays, list(shape=TRUE, separation=FALSE))
  expect_identical(o$minPlayers, 3L)
  expect_identical(o$excludeEntities, list("a"))
  json <- jsonlite::toJSON(o, auto_unbox=TRUE)
  expect_match(json, '"excludeEntities":["a"]', fixed=TRUE)
  expect_match(json, '"metricWindow":[0,0.2]', fixed=TRUE)
  expect_identical(field(excludeEntities=c(11, 25))$x$config$layers[[1]]$options$excludeEntities, list("11", "25"))
  expect_null(field(pitchLength=105)$x$config$layers[[1]]$options$overlays)
  expect_error(field(overlays=list(shape="yes")), "overlays")
  expect_error(field(overlays=list(pitchControl=TRUE)), "overlays")
  expect_error(field(overlays=TRUE), "overlays")
  expect_error(field(minPlayers=1), "minPlayers")
  expect_error(field(minPlayers=2.5), "minPlayers")
  expect_error(field(excludeEntities=c("a", NA)), "excludeEntities")
  expect_error(field(metricWindow=c(5, 1)), "metricWindow")
  expect_error(field(metricWindow=3), "metricWindow")
  expect_error(field(metricWindow=c(0, Inf)), "metricWindow")
})
